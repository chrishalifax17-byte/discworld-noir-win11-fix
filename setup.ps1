<#
.SYNOPSIS
  Per-user setup for the patched Discworld Noir (run after patch_noir.py).

.DESCRIPTION
  - Creates HKCU\SOFTWARE\Perfect Entertainment\Discworld Noir, copying any
    settings the original installer left under HKLM, and points "HD Path" at
    your game folder.
  - Writes "Play Discworld Noir.bat" into the game folder. It mounts your
    disc image (the game checks for a CD) and starts the game.
  - Optionally creates Desktop and Start menu shortcuts.
  No admin rights are needed.

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File setup.ps1 -GameDir "C:\DiscNoir" -DiscImage "D:\Images\DWN_ENG_1.iso" -Shortcuts
#>
param(
  [Parameter(Mandatory = $true)][string]$GameDir,
  [string]$DiscImage = "",
  [switch]$Shortcuts
)
$ErrorActionPreference = "Stop"
$GameDir = (Resolve-Path $GameDir).Path.TrimEnd('\')
$exe = Join-Path $GameDir "tin3_dxd.exe"
if (-not (Test-Path $exe)) { throw "tin3_dxd.exe not found in $GameDir" }
if ($DiscImage) { $DiscImage = (Resolve-Path $DiscImage).Path }

$hkcu = "HKCU:\SOFTWARE\Perfect Entertainment\Discworld Noir"
$hklm = "HKLM:\SOFTWARE\WOW6432Node\Perfect Entertainment\Discworld Noir"
New-Item $hkcu -Force | Out-Null
if (Test-Path $hklm) {
  $src = Get-ItemProperty $hklm
  foreach ($p in $src.PSObject.Properties) {
    if ($p.Name -notlike 'PS*' -and $p.Name -ne 'Last Error' -and
        -not (Get-ItemProperty $hkcu -Name $p.Name -ErrorAction SilentlyContinue)) {
      New-ItemProperty $hkcu -Name $p.Name -Value ([string]$p.Value) -PropertyType String -Force | Out-Null
    }
  }
}
Set-ItemProperty $hkcu -Name "HD Path" -Value $GameDir
Set-ItemProperty $hkcu -Name "Install Path" -Value $GameDir
if (-not (Get-ItemProperty $hkcu -Name "Sample Path" -ErrorAction SilentlyContinue)) {
  Set-ItemProperty $hkcu -Name "Sample Path" -Value (Join-Path $GameDir "cd1")
}
Set-ItemProperty $hkcu -Name "Start Windowed" -Value "Yes"   # patched exe is always borderless-windowed
$dolomite = Join-Path $GameDir "ddraw.dll"
if (-not (Test-Path $dolomite)) {
  Write-Warning "ddraw.dll (dolomite) not found in $GameDir - colours will be wrong without it. See README."
}
Write-Host "Settings written to $hkcu"

$bat = Join-Path $GameDir "Play Discworld Noir.bat"
$mount = ""
if ($DiscImage) {
  $mount = @"
powershell -NoProfile -ExecutionPolicy Bypass -Command "if (-not (Get-DiskImage -ImagePath '$DiscImage').Attached) { Mount-DiskImage -ImagePath '$DiscImage' | Out-Null }"
"@
}
@"
@echo off
rem Discworld Noir launcher (generated by setup.ps1)
$mount
start "" /D "$GameDir" "$exe"
"@ | Set-Content -Path $bat -Encoding ASCII
Write-Host "Launcher written to $bat"
if (-not $DiscImage) {
  Write-Host "No -DiscImage given: insert or mount a game disc before playing."
}

if ($Shortcuts) {
  $sh = New-Object -ComObject WScript.Shell
  foreach ($dir in [Environment]::GetFolderPath('Desktop'), [Environment]::GetFolderPath('Programs')) {
    $l = $sh.CreateShortcut((Join-Path $dir "Discworld Noir.lnk"))
    $l.TargetPath = $bat
    $l.WorkingDirectory = $GameDir
    $l.IconLocation = "$exe,0"
    $l.WindowStyle = 7
    $l.Description = "Discworld Noir"
    $l.Save()
    Write-Host "Shortcut created in $dir"
  }
}
