#!/bin/sh
# Builds noirpad.c into a raw blob linked at 0x5D6200 and writes
# ../noirpad_blob.py for patch_noir.py.  Needs a GCC + binutils that can
# target 32-bit PE (e.g. MSYS2 UCRT64 gcc with -m32, or mingw32 gcc) and Python 3.
set -e
cd "$(dirname "$0")"
BASE=0x5D6200
RDATA=0x5D6700
gcc -m32 -Os -ffreestanding -fno-builtin -fno-pic -fno-asynchronous-unwind-tables \
    -fno-stack-protector -mno-sse -mno-mmx -mpreferred-stack-boundary=2 \
    -Wall -Wextra -c noirpad.c -o noirpad.o
ld -m i386pe -nostdlib -e _pad_hook -Ttext=$BASE --section-start=.rdata=$RDATA \
    -o noirpad.exe noirpad.o
objcopy -O binary -j .text -j .rdata noirpad.exe noirpad.bin
HOOK=0x$(nm noirpad.exe | awk '$3 == "_pad_hook" { print $1 }')
PY=python3
command -v py >/dev/null 2>&1 && PY="py -3"
$PY - "$BASE" "$HOOK" <<'EOF'
import sys
base, hook = sys.argv[1], sys.argv[2]
blob = open("noirpad.bin", "rb").read()
with open("../noirpad_blob.py", "w") as f:
    f.write("# Generated by controller/build.sh from controller/noirpad.c - do not edit.\n")
    f.write(f"BASE = {base}\nHOOK = {hook}\nBLOB = bytes.fromhex(\n")
    for i in range(0, len(blob), 32):
        f.write(f'    "{blob[i:i + 32].hex()}"\n')
    f.write(")\n")
print(f"noirpad: {len(blob)} bytes at {base}, hook at {hook}")
EOF
rm -f noirpad.o noirpad.exe noirpad.bin
